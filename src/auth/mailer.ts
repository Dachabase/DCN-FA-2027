/**
 * Email delivery through the Brevo HTTP API (works on Render's free tier).
 * Env vars: BREVO_API_KEY, MAIL_FROM_EMAIL (a sender verified in Brevo), MAIL_FROM_NAME (optional).
 */

const BRAND = "#7C3AED";
const INK = "#0F172A";
const MUTED = "#64748B";

export async function sendMail(to: string, subject: string, html: string): Promise<boolean> {
  const apiKey = process.env.BREVO_API_KEY;
  const fromEmail = process.env.MAIL_FROM_EMAIL;
  if (!apiKey || !fromEmail) {
    console.warn("[mailer] BREVO_API_KEY / MAIL_FROM_EMAIL are not set, so no email was sent.");
    return false;
  }
  try {
    const res = await fetch("https://api.brevo.com/v3/smtp/email", {
      method: "POST",
      headers: { "api-key": apiKey, "Content-Type": "application/json", accept: "application/json" },
      body: JSON.stringify({
        sender: { email: fromEmail, name: process.env.MAIL_FROM_NAME || "BlastExams" },
        to: [{ email: to }],
        subject,
        htmlContent: html,
      }),
    });
    if (!res.ok) {
      console.error("[mailer] Brevo error", res.status, await res.text().catch(() => ""));
      return false;
    }
    return true;
  } catch (err) {
    console.error("[mailer] Could not reach Brevo:", err);
    return false;
  }
}

function layout(title: string, bodyHtml: string): string {
  return `<div style="font-family:Arial,Helvetica,sans-serif;max-width:440px;margin:auto;padding:28px;color:${INK}">
    <h2 style="margin:0 0 16px;color:${BRAND}">BlastExams</h2>
    <h3 style="margin:0 0 12px">${title}</h3>
    ${bodyHtml}
    <p style="margin-top:24px;font-size:12px;color:${MUTED}">If you did not request this, you can safely ignore this email.</p>
  </div>`;
}

function codeBlock(code: string): string {
  return `<p style="font-size:34px;font-weight:bold;letter-spacing:10px;margin:16px 0;color:${INK}">${code}</p>`;
}

/** `code` is always six digits generated by us, so it is safe to place in HTML. */
export function sendVerificationCode(to: string, code: string): Promise<boolean> {
  return sendMail(
    to,
    `Your BlastExams verification code: ${code}`,
    layout(
      "Confirm your email",
      `<p>Enter this code to finish creating your account:</p>${codeBlock(code)}
       <p style="color:${MUTED}">It expires in 15 minutes.</p>`
    )
  );
}

export function sendPasswordResetCode(to: string, code: string): Promise<boolean> {
  return sendMail(
    to,
    `Your BlastExams password reset code: ${code}`,
    layout(
      "Reset your password",
      `<p>Enter this code, together with your new password, to reset it:</p>${codeBlock(code)}
       <p style="color:${MUTED}">It expires in 15 minutes and works once.</p>`
    )
  );
}

export function sendAccountExistsNotice(to: string): Promise<boolean> {
  return sendMail(
    to,
    "You already have a BlastExams account",
    layout(
      "You already have an account",
      `<p>Someone tried to create a BlastExams account with this email address, but one already exists.</p>
       <p>You can sign in, or use <b>Forgot password</b> on the sign-in screen if you need to set or change your password.</p>`
    )
  );
}
