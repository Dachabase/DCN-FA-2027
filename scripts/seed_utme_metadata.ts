async function seed() {
  console.log("Seeding UTME Subjects...");
  for (const s of UTME_SUBJECTS) {
    await prisma.utmeSubject.upsert({
      where: { code: s.code },
      update: {
        name: s.name,
        description: s.description,
        icon: s.icon,
        questionCount: s.questionCount,
        durationMinutes: s.durationMinutes,
        isCompulsory: s.isCompulsory,
        syllabusTopics: s.syllabusTopics,
      },
      create: s,
    });
    console.log(` - Seeded subject: ${s.name} (${s.code})`);
  }

  console.log("\nSeeding UTME Course Combinations...");
  for (const c of UTME_COURSE_COMBINATIONS) {
    await prisma.utmeCourseCombination.upsert({
      where: { slug: c.slug },
      update: {
        courseName: c.courseName,
        facultyName: c.facultyName,
        degreeType: c.degreeType,
        compulsorySubjects: c.compulsorySubjects,
        alternativeSubjects: c.alternativeSubjects,
        subjectCodes: c.subjectCodes,
        notes: c.notes,
        institutionNotes: c.institutionNotes,
        officialSource: c.officialSource,
        verifiedDate: new Date(),
      },
      create: c,
    });
    console.log(` - Seeded course combination: ${c.courseName} -> [${c.compulsorySubjects.join(", ")}]`);
  }

  console.log("\nSeeding completed successfully!");
}

seed()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error("Seeding error:", err);
    process.exit(1);
  });
